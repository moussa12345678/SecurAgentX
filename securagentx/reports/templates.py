"""Built-in report & vulnerability template strings plus a tiny render engine.

This module is intentionally dependency-free: every template is a plain
multi-line ``str`` that uses ``{placeholder}`` substitution.  The
:func:`render_template` helper substitutes every recognised placeholder
with the matching context value **or** an empty string (so a partial
context never raises ``KeyError`` and never leaves a literal ``{...}``
behind in the rendered output).

Public surface
--------------

Templates (module-level ``str`` constants):
    * ``DEFAULT_TEMPLATE``              — standard pentest report skeleton
    * ``EXECUTIVE_SUMMARY_TEMPLATE``    — short executive summary
    * ``DETAILED_FINDINGS_TEMPLATE``    — full findings w/ CVSS, evidence, fixes
    * ``COMPLIANCE_REPORT_TEMPLATE``    — PCI-DSS / SOC 2 / ISO-IEC 27001 mapping
                                          (alias: ``COMPLIANCE_TEMPLATE``)
    * ``VULNERABILITY_TEMPLATE``        — single-vuln report (CVE-centric)
                                          (alias: ``VULNERABILITY_REPORT_TEMPLATE``)
    * ``TECHNICAL_REPORT_TEMPLATE``     — full technical / methodology report

Functions:
    * ``get_template(name)      -> str``       — look up a template by name
    * ``list_templates()        -> list[str]`` — sorted list of template names
    * ``validate_template(name) -> bool``      — membership check
    * ``render_template(tpl, ctx) -> str``     — render a template string (or
                                                  registered name) with a context

Class:
    * ``TemplateEngine``                      — stateful engine that can register
                                                 custom templates and render by
                                                 name.
"""

