# ---------------------------------------------------------------------------
# 3. Render helpers
# ---------------------------------------------------------------------------

# Matches ``{identifier}`` where *identifier* is a Python-style name.  We do
# **not** use :class:`string.Formatter` because it would raise on unknown
# keys, attribute access, or stray braces; the brutal test-suite requires that
# missing keys silently become empty strings and that the rendered output
# contain **no** literal ``{`` characters.
_PLACEHOLDER_RE = re.compile(r"\{([a-zA-Z_][a-zA-Z0-9_]*)\}")


def _substitute(template: str, context: Optional[Dict[str, Any]]) -> str:
    """Substitute every ``{name}`` placeholder in *template*.

    Each placeholder is replaced with ``str(context[name])`` when *name* is
    present in *context*, otherwise with an empty string.  This guarantees a
    KeyError-free render and an output free of unsubstituted ``{...}``
    markers (provided the template itself only uses ``{identifier}``
    placeholders, which all built-in templates do).
    """
    ctx: Dict[str, Any] = dict(context) if context else {}

    def _replace(match: "re.Match[str]") -> str:
        key = match.group(1)
        if key in ctx:
            value = ctx[key]
            return "" if value is None else str(value)
        return ""

    return _PLACEHOLDER_RE.sub(_replace, template)


def render_template(template: str, context: Optional[Dict[str, Any]] = None) -> str:
    """Render *template* (a template string **or** a registered name) with *context*.

    The first argument may be either:

    * the literal template string (e.g. ``VULNERABILITY_TEMPLATE``), or
    * a registered template name (e.g. ``"vulnerability"``).

    Every ``{placeholder}`` is replaced with the corresponding context value
    (coerced via ``str``) or — when absent — with an empty string.  No
    ``KeyError`` is ever raised and the result never contains an
    unsubstituted ``{...}`` marker.
    """
    if not isinstance(template, str):
        raise TypeError(
            "render_template() expected str for 'template', got "
            f"{type(template).__name__}"
        )
    # If the caller passed a registered *name*, resolve it to the template
    # string.  This keeps the function flexible: it works both as
    # ``render_template("vulnerability", ctx)`` and as
    # ``render_template(VULNERABILITY_TEMPLATE, ctx)``.
    if template in _TEMPLATES:
        template = _TEMPLATES[template]
    return _substitute(template, context)


def get_template(name: str) -> str:
    """Return the template string registered under *name*.

    Raises :class:`KeyError` if *name* is unknown.
    """
    if name not in _TEMPLATES:
        raise KeyError(
            f"Unknown template name: {name!r}. "
            f"Available: {list_templates()}"
        )
    return _TEMPLATES[name]


def list_templates() -> List[str]:
    """Return a sorted list of all registered template names (including aliases)."""
    return sorted(_TEMPLATES.keys())


def validate_template(name: str) -> bool:
    """Return ``True`` if *name* is a registered template name."""
    return name in _TEMPLATES


# ---------------------------------------------------------------------------
# 4. TemplateEngine — stateful, registerable render engine
# ---------------------------------------------------------------------------

class TemplateEngine:
    """A small stateful engine around the template registry.

    A fresh engine starts with a **copy** of the built-in registry so that
    :meth:`register_template` calls do not mutate module-level state.
    """

    def __init__(self) -> None:
        self._templates: Dict[str, str] = dict(_TEMPLATES)

    # -- registration ------------------------------------------------------

    def register_template(self, name: str, template: str) -> None:
        """Register (or overwrite) a custom template under *name*."""
        if not isinstance(name, str) or not name:
            raise ValueError("template name must be a non-empty string")
        if not isinstance(template, str):
            raise TypeError("template must be a string")
        self._templates[name] = template

    def unregister_template(self, name: str) -> bool:
        """Remove a registered template.  Returns ``True`` if it existed."""
        return self._templates.pop(name, None) is not None

    # -- queries -----------------------------------------------------------

    def get(self, name: str) -> str:
        """Return the template string for *name* (raises ``KeyError`` if unknown)."""
        if name not in self._templates:
            raise KeyError(f"Unknown template name: {name!r}")
        return self._templates[name]

    def has(self, name: str) -> bool:
        """Return ``True`` if *name* is registered in this engine."""
        return name in self._templates

    def list(self) -> List[str]:
        """Return a sorted list of template names known to this engine."""
        return sorted(self._templates.keys())

    # convenience aliases that mirror the module-level API
    def validate(self, name: str) -> bool:
        """Alias for :meth:`has`."""
        return self.has(name)

    # -- rendering ---------------------------------------------------------

    def render(self, name: str, context: Optional[Dict[str, Any]] = None) -> str:
        """Render the template registered under *name* with *context*.

        If *name* is not registered it is treated as a literal template
        string and rendered directly (matching :func:`render_template`'s
        forgiving behaviour).
        """
        template = self._templates.get(name, name)
        return _substitute(template, context)

    def render_string(self, template: str, context: Optional[Dict[str, Any]] = None) -> str:
        """Render an ad-hoc *template* string (not a registered name) with *context*."""
        return _substitute(template, context)

    # -- dunder ------------------------------------------------------------

    def __contains__(self, name: object) -> bool:
        return isinstance(name, str) and name in self._templates

    def __len__(self) -> int:
        return len(self._templates)

    def __repr__(self) -> str:  # pragma: no cover - trivial
        return f"TemplateEngine(templates={len(self._templates)})"
